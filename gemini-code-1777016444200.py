# =====================================================
# 📊 假財報（避免解析失敗）
# =====================================================

def financial_data():

    return pd.DataFrame({
        "年度": ["2022", "2023", "2024"],
        "營收": [100, 120, 90],
        "獲利": [10, 15, -5],
        "資產": [200, 220, 210],
        "負債": [80, 100, 130]
    })


# =====================================================
# 🧠 財報分析（全部整合）
# =====================================================

def analyze(df):

    result = {
        "四大報表分析": [],
        "風險分析": [],
        "查核建議": [],
        "年度分析": []
    }


    # =========================
    # 四大報表
    # =========================

    result["四大報表分析"] = [
        "資產負債表分析",
        "損益表分析",
        "現金流量分析",
        "權益變動分析"
    ]


    # =========================
    # 舞弊 / 掏空 / 不實
    # =========================

    if df["獲利"].iloc[-1] < 0:
        result["風險分析"].append("財報虧損風險")

    if df["負債"].iloc[-1] > df["負債"].iloc[0]:
        result["風險分析"].append("負債上升風險")

    result["風險分析"] += [
        "財報不實風險",
        "掏空風險（資金異常流動）",
        "關係人交易風險",
        "舞弊風險"
    ]


    # =========================
    # 查核建議（ISA 概念）
    # =========================

    result["查核建議"] = [
        "收入認列測試",
        "應收帳款函證",
        "存貨盤點",
        "關係人交易查核",
        "現金流量測試",
        "內控測試"
    ]


    # =========================
    # 年度分析
    # =========================

    if df["營收"].iloc[-1] < df["營收"].iloc[0]:
        result["年度分析"].append("營收下降趨勢")

    if df["獲利"].iloc[-1] < 0:
        result["年度分析"].append("出現虧損")

    if df["負債"].iloc[-1] > df["負債"].iloc[0]:
        result["年度分析"].append("負債增加")


    return result


# =====================================================
# 📊 圖表
# =====================================================

def chart(df):

    fig, ax = plt.subplots()

    ax.plot(df["年度"], df["營收"], label="營收")
    ax.plot(df["年度"], df["獲利"], label="獲利")

    ax.set_title("財務趨勢")
    ax.legend()

    return fig


# =====================================================
# 🚀 主流程
# =====================================================

if files:

    df = financial_data()

    analysis = analyze(df)


    st.subheader("📊 四大報表分析")
    st.write(analysis["四大報表分析"])


    st.subheader("⚠️ 風險分析")
    st.write(analysis["風險分析"])


    st.subheader("🧾 查核建議")
    st.write(analysis["查核建議"])


    st.subheader("📈 年度分析")
    st.write(analysis["年度分析"])


    st.subheader("📊 圖表")
    st.pyplot(chart(df))
